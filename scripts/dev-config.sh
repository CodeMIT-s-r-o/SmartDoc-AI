#!/usr/bin/env bash
# Writes .env.dev-aws: the dev stacks' non-secret config (from SSM), read by compose (api, web).
# Usage: AWS_PROFILE=codemit scripts/dev-config.sh [output-file]
set -euo pipefail

stage=${STAGE:-dev}
region=eu-central-1
out=${1:-.env.dev-aws}
path="/smartdoc/${stage}/config/"

params=$(aws ssm get-parameters-by-path --path "$path" --region "$region" \
  --query 'Parameters[].[Name,Value]' --output text)

get() {
  local value
  value=$(awk -v name="${path}$1" '$1 == name { print $2 }' <<<"$params")
  if [[ -z $value ]]; then
    echo "Missing SSM parameter ${path}$1. Deploy the ${stage} stacks first (make cdk-dev)." >&2
    exit 1
  fi
  printf '%s' "$value"
}

cat >"$out" <<ENV
# Generated by scripts/dev-config.sh from SSM ${path} (non-secret). Do not edit by hand.
AWS_REGION=${region}
S3_DOCS_BUCKET=$(get docs_bucket)
COGNITO_USER_POOL_ID=$(get cognito_user_pool_id)
COGNITO_CLIENT_ID=$(get cognito_client_id)
COGNITO_DOMAIN=$(get cognito_domain)
VITE_OIDC_AUTHORITY=$(get oidc_authority)
VITE_OIDC_CLIENT_ID=$(get cognito_client_id)
VITE_OIDC_REDIRECT_URI=http://localhost:5173/auth/callback
VITE_COGNITO_DOMAIN=$(get cognito_domain)
ENV
echo "Wrote ${out}"
